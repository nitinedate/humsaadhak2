-- Roles and permissions managed by super admins (Roles and permissions screen).
--   app_permission       every right a role can grant. System permissions are checked by the application's code; custom
--                        ones are added by administrators for new features and integrations.
--   app_role             assignable roles. "kind" is the account type (staff, donor, school, NGO), which decides whose data
--                        a person works with and which dashboard they get; the role's permissions decide what they can do.
--   app_role_permission  which permissions each role grants.
--   access_change_log    who changed roles and permissions, and how.
-- The previous fixed roles become system roles with exactly the permissions they had in code.

create table app_permission (
  code varchar(80) primary key, name varchar(120) not null, description varchar(500), category varchar(60) not null,
  system boolean not null default false, created_at timestamptz not null default now(), created_by varchar(255)
);
create table app_role (
  code varchar(60) primary key, name varchar(120) not null unique, description varchar(500), kind varchar(30) not null,
  system boolean not null default false, created_at timestamptz not null default now(), created_by varchar(255), updated_at timestamptz
);
create table app_role_permission (
  role_code varchar(60) not null references app_role(code) on delete cascade,
  permission_code varchar(80) not null references app_permission(code) on delete cascade,
  primary key (role_code, permission_code)
);
create table access_change_log (
  id bigint generated by default as identity primary key, at timestamptz not null default now(), actor varchar(255) not null,
  action varchar(40) not null, subject varchar(120) not null, details varchar(2000)
);
create index ix_access_change_log_at on access_change_log(at desc);

