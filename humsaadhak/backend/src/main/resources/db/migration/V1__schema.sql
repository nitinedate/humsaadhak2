  ref_no varchar(20) unique, batch_id bigint not null references match_batch(id), candidate_id bigint not null references match_candidate(id),
  purpose_id bigint not null references purpose(id), need_id bigint not null references need(id),
  donor_org_id bigint not null references organisation(id), priority integer not null,
  unique (purpose_id, need_id)
