);

create table match_candidate (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null, created_by varchar(255), updated_at timestamptz, updated_by varchar(255), version bigint not null default 0,
  run_id bigint not null references match_run(id), purpose_id bigint not null references purpose(id), need_id bigint not null references need(id),
  retrieval_score double precision, rerank_score double precision, final_score integer not null check (final_score between 0 and 100),
