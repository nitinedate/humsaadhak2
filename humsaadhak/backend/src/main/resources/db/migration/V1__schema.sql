-- Envers history tables: same columns as the base table, all nullable, plus rev / revtype.
create or replace function create_audit_table(t text) returns void language plpgsql as $$
declare c record;
begin
  execute format('create table %I (like %I)', t || '_aud', t);
  for c in select column_name from information_schema.columns
           where table_schema = current_schema() and table_name = t || '_aud' and column_name <> 'id' loop
    execute format('alter table %I alter column %I drop not null', t || '_aud', c.column_name);
  end loop;
  execute format('alter table %I add column rev integer not null references revinfo(rev), add column revtype smallint, add primary key (id, rev)', t || '_aud');
end $$;

select create_audit_table(t) from unnest(array['app_user','organisation','purpose','need','document','match_candidate','donation']) as t;
drop function create_audit_table(text);
