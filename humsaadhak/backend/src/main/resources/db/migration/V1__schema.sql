create table document (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null, created_by varchar(255), updated_at timestamptz, updated_by varchar(255), version bigint not null default 0,
  owner_org_id bigint not null references organisation(id), document_type_id bigint not null references document_type(id),
  need_id bigint references need(id), donation_id bigint, storage_key varchar(400) not null unique,
