create table share_request (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null, created_by varchar(255), updated_at timestamptz, updated_by varchar(255), version bigint not null default 0,
  need_id bigint not null references need(id), owner_org_id bigint not null references organisation(id),
  donor_org_id bigint not null references organisation(id), status varchar(20) not null, reason varchar(2000),
  unique (need_id, donor_org_id)
