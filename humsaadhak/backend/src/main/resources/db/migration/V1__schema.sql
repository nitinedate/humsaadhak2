-- HumSaadhak 2.0 schema. Every business table carries the same audit columns and an optimistic-lock version.
create extension if not exists vector;
create schema if not exists search;   -- owned by the Python search service

create sequence revinfo_seq start with 1 increment by 50;
create table revinfo (rev integer primary key, revtstmp bigint);

create table app_user (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null, created_by varchar(255), updated_at timestamptz, updated_by varchar(255), version bigint not null default 0,
  email varchar(320) not null unique, full_name varchar(255) not null, mobile varchar(32), password_hash varchar(255),
  org_id bigint, role varchar(40) not null, status varchar(20) not null,
  failed_logins integer not null default 0, locked_until timestamptz, totp_secret varchar(255)
);
create index ix_app_user_org on app_user(org_id);

create table one_time_token (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null, created_by varchar(255), updated_at timestamptz, updated_by varchar(255), version bigint not null default 0,
  user_id bigint not null references app_user(id), purpose varchar(20) not null,
  token_hash varchar(64) not null unique, expires_at timestamptz not null, used_at timestamptz
);

create table organisation (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null, created_by varchar(255), updated_at timestamptz, updated_by varchar(255), version bigint not null default 0,
  ref_no varchar(20) unique, name varchar(300) not null, type varchar(30) not null,
  city varchar(120), state varchar(120), pan_masked varchar(20), verified boolean not null default false, legacy_id bigint
);
create index ix_org_name_type on organisation(lower(name), type);
alter table app_user add constraint fk_user_org foreign key (org_id) references organisation(id);

create table org_contact (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null, created_by varchar(255), updated_at timestamptz, updated_by varchar(255), version bigint not null default 0,
  org_id bigint not null references organisation(id), role varchar(20) not null, name varchar(255) not null,
  designation varchar(255), email varchar(320), phone varchar(32)
);

create table bank_account (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null, created_by varchar(255), updated_at timestamptz, updated_by varchar(255), version bigint not null default 0,
  org_id bigint not null references organisation(id), account_name varchar(255) not null, account_number varchar(34) not null,
  ifsc varchar(11) not null, bank_name varchar(255), branch varchar(255)
);

create table approval_request (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null, created_by varchar(255), updated_at timestamptz, updated_by varchar(255), version bigint not null default 0,
  subject_type varchar(30) not null, subject_id bigint not null, maker_id bigint not null,
  status varchar(20) not null, revision integer not null default 1, last_comment varchar(2000), subject_title varchar(300),
  unique (subject_type, subject_id)
);
create index ix_approval_status on approval_request(status, subject_type, updated_at);

create table approval_step (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null, created_by varchar(255), updated_at timestamptz, updated_by varchar(255), version bigint not null default 0,
  request_id bigint not null references approval_request(id), from_status varchar(20), to_status varchar(20) not null,
  actor_id bigint not null, comment varchar(2000)
);

create table purpose (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null, created_by varchar(255), updated_at timestamptz, updated_by varchar(255), version bigint not null default 0,
  ref_no varchar(20) unique, donor_org_id bigint not null references organisation(id), name varchar(300) not null,
  description varchar(8000) not null, sector varchar(80) not null, commitment_amount numeric(14,2),
  periodicity varchar(20) not null, approved boolean not null default false, matched boolean not null default false,
  completed boolean not null default false
);

create table need (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null, created_by varchar(255), updated_at timestamptz, updated_by varchar(255), version bigint not null default 0,
  ref_no varchar(20) unique, org_id bigint not null references organisation(id), kind varchar(10) not null,
  name varchar(300) not null, description varchar(8000) not null, sector varchar(80) not null,
  target_amount numeric(14,2) not null check (target_amount > 0), raised_amount numeric(14,2) not null default 0,
  periodicity varchar(20) not null, approved boolean not null default false, completed boolean not null default false
);
create index ix_need_org on need(org_id);

create table document_type (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null, created_by varchar(255), updated_at timestamptz, updated_by varchar(255), version bigint not null default 0,
  code varchar(60) not null unique, name varchar(255) not null, category varchar(30) not null, shareable boolean not null default false
