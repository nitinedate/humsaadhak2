create table match_batch (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null, created_by varchar(255), updated_at timestamptz, updated_by varchar(255), version bigint not null default 0,
  ref_no varchar(20) unique, purpose_id bigint not null references purpose(id), confirmed_by bigint not null
