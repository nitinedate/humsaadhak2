create table document_type_rule (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null, created_by varchar(255), updated_at timestamptz, updated_by varchar(255), version bigint not null default 0,
  document_type_id bigint not null references document_type(id), organisation_type varchar(30) not null, mandatory boolean not null,
  unique (document_type_id, organisation_type)
