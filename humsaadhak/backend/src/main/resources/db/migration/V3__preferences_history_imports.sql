-- Theme saved per user (Settings), the acting user on every history revision, and bulk-import bookkeeping.
alter table app_user add column theme varchar(20) not null default 'INDIGO';
alter table app_user_aud add column theme varchar(20);
alter table revinfo add column username varchar(255);

create table import_job (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null, created_by varchar(255), updated_at timestamptz, updated_by varchar(255), version bigint not null default 0,
  type varchar(20) not null, file_name varchar(255) not null, status varchar(20) not null,
  row_count integer not null default 0, created_count integer not null default 0, error_count integer not null default 0
);

create table import_row_error (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null, created_by varchar(255), updated_at timestamptz, updated_by varchar(255), version bigint not null default 0,
  job_id bigint not null references import_job(id), row_number integer not null, column_name varchar(80) not null, message varchar(500) not null
);
create index ix_import_error_job on import_row_error(job_id, row_number);

