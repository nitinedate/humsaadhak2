"""What the services need from storage. Implemented by InMemoryStore (tests, demos) and PgVectorStore (production)."""
from typing import Protocol

import numpy as np

from app.model.card import Card
from app.model.label import Label
from app.model.stored_doc import StoredDoc


class VectorStore(Protocol):
    def upsert(self, card: Card, vector: np.ndarray, text_hash: str) -> None: ...
    def delete(self, entity_type: str, entity_id: int) -> None: ...
    def get(self, entity_type: str, entity_id: int) -> StoredDoc | None: ...
    def dense_search(self, entity_type: str, query: np.ndarray, k: int, sector: str | None = None) -> list[tuple[int, float]]: ...
    def keyword_search(self, entity_type: str, query_text: str, k: int, sector: str | None = None) -> list[tuple[int, float]]: ...
    def all_ids(self, entity_type: str) -> list[int]: ...
    def add_labels(self, labels: list[Label]) -> None: ...
    def labels(self) -> list[Label]: ...
